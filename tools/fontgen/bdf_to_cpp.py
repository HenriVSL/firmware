"""Converts fixed-cell BDF fonts into C++ glyph tables for dmm::services.

Usage: bdf_to_cpp.py <font.bdf> <name> <last code point> <output.cpp>

Writes code points 32 up to the given last one (126 or 255). A glyph the
font lacks becomes a copy of '?'. Rows are stored MSB first, glyph after
glyph, as in the BDF file.
"""
import sys
from pathlib import Path


def parse(path):
    glyphs, cell, props = {}, None, {}
    lines = Path(path).read_text(encoding="ascii", errors="replace").splitlines()
    i = 0
    while i < len(lines):
        parts = lines[i].split()
        if not parts:
            i += 1
            continue
        if parts[0] == "FONTBOUNDINGBOX":
            cell = tuple(int(x) for x in parts[1:5])
        elif parts[0] == "COPYRIGHT":
            props["copyright"] = lines[i].split(" ", 1)[1].strip('"')
        elif parts[0] == "STARTCHAR":
            code, bbx, rows = None, None, []
            while True:
                i += 1
                p = lines[i].split()
                if p[0] == "ENCODING":
                    code = int(p[1])
                elif p[0] == "BBX":
                    bbx = tuple(int(x) for x in p[1:5])
                elif p[0] == "BITMAP":
                    while True:
                        i += 1
                        if lines[i].startswith("ENDCHAR"):
                            break
                        rows.append(int(lines[i], 16))
                    break
            if bbx != cell:
                sys.exit(f"{path}: glyph {code} is not a full cell ({bbx} vs {cell})")
            glyphs[code] = rows
        i += 1
    return cell, glyphs, props


def main():
    src, name, last, out = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4]
    (w, h, _, _), glyphs, props = parse(src)
    bytes_per_row = (w + 7) // 8
    data = []
    for code in range(32, last + 1):
        rows = glyphs.get(code, glyphs[ord("?")])
        for r in rows:
            data.extend(r.to_bytes(bytes_per_row, "big"))
    body = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in data[k:k + 16]) for k in range(0, len(data), 16))
    Path(out).write_text(f"""// SPDX-License-Identifier: BSD-2-Clause
// SPDX-FileCopyrightText: {props.get('copyright', 'Copyright (c) Frederic Cambus')}
// Generated by tools/fontgen/bdf_to_cpp.py from third_party/spleen/{Path(src).name}; do not edit.

#include "dmm/services/font.h"

namespace dmm::services::fonts {{

namespace {{

constexpr std::uint8_t Glyphs[] = {{
{body}}};

}} // namespace

const Font {name}{{{w}, {h}, 32, {last}, Glyphs}};

}} // namespace dmm::services::fonts
""", encoding="ascii")


if __name__ == "__main__":
    main()
